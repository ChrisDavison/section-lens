import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import process from 'node:process';

const json = async path => JSON.parse(await readFile(path, 'utf8'));
const manifest = await json('manifest.json');
const pkg = await json('package.json');
const lock = await json('package-lock.json');
const versions = await json('versions.json');
assert.match(manifest.id, /^[a-z]+(?:-[a-z]+)*$/);
assert.ok(!manifest.id.includes('obsidian') && !manifest.id.endsWith('plugin'));
assert.ok(!/obsidian|plugin/i.test(manifest.name));
assert.match(manifest.version, /^\d+\.\d+\.\d+$/);
assert.equal(pkg.version, manifest.version);
assert.equal(lock.version, manifest.version);
assert.equal(lock.packages[''].version, manifest.version);
assert.equal(versions[manifest.version], manifest.minAppVersion);
if (process.env.RELEASE_TAG) assert.equal(manifest.version, process.env.RELEASE_TAG, 'Release tag must match manifest version');
assert.ok(manifest.description.length <= 250 && manifest.description.endsWith('.'));
assert.equal(manifest.author, 'Chris Davison');
assert.equal(manifest.authorUrl, 'https://github.com/ChrisDavison');
assert.equal(typeof manifest.isDesktopOnly, 'boolean');
for (const name of ['README.md', 'LICENSE', 'THIRD-PARTY-NOTICES.txt', 'main.js']) assert.ok((await readFile(name)).length > 0);
const bundle = await readFile('main.js', 'utf8');
const allowed = new Set(['obsidian', '@codemirror/view', '@codemirror/state', '@codemirror/language']);
for (const match of bundle.matchAll(/require\("([^"]+)"\)/g)) assert.ok(allowed.has(match[1]), `Unexpected runtime import: ${match[1]}`);
assert.ok(bundle.includes(await readFile('THIRD-PARTY-NOTICES.txt', 'utf8')));
assert.ok(!bundle.includes('sourceMappingURL'));
console.info('Release metadata, runtime imports, and license checks passed.');
